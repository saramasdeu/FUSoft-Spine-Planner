"""
finetune_sitiny.py
------------------
Fine-tunes the pre-trained Sitiny ShuffleUNet on paired MRI/CT patches.
Uses knowledge distillation to prevent catastrophic forgetting:
  total_loss = TASK_ALPHA * L1(pred, ct_target)
             + DISTILL_ALPHA * MSE(pred, teacher_pred)

Patch format (generated by creation_patches.py):
  <PATCHES_DIR>/<subject_id>_patch_<i>_mri.npy   shape (64, 128, 128) float32  range [-1, 1]
  <PATCHES_DIR>/<subject_id>_patch_<i>_ct.npy    shape (64, 128, 128) float32  range [-1, 1]

Usage (server, from this file's directory):
  python finetune_sitiny.py

Or override paths via environment variables:
  PATCHES_DIR=/path/to/patches  MODEL_IN=/path/to/pretrained.pth  python finetune_sitiny.py
"""

import os, sys, glob, time, copy
import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader, random_split

# ---------------------------------------------------------------------------
# PATHS  (edit here or set env variables)
# ---------------------------------------------------------------------------
SCRIPT_DIR   = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT    = os.path.dirname(os.path.dirname(SCRIPT_DIR))   # TFG_FUSOFT parent or itself

SITINY_REPO  = os.environ.get(
    "SITINY_REPO",
    "/home/sara/FUSoft-Spine-Planner/stinity_mr-to-pct",
)
# Fallback: look relative to this script
if not os.path.isdir(SITINY_REPO):
    SITINY_REPO = os.path.join(SCRIPT_DIR, "..", "Pseudo_CTS", "stinity_mr-to-pct")

PATCHES_DIR  = os.environ.get(
    "PATCHES_DIR",
    os.path.join(REPO_ROOT, "DATASET_NET", "patches"),
)
if not os.path.isdir(PATCHES_DIR):
    PATCHES_DIR = "/home/sara/FUSoft-Spine-Planner/DATASET_NET/patches"

MODEL_IN     = os.environ.get(
    "MODEL_IN",
    os.path.join(REPO_ROOT, "TFG_FUSOFT", "models", "pretrained_net_final_20220825.pth"),
)
if not os.path.exists(MODEL_IN):
    MODEL_IN = "/home/sara/FUSoft-Spine-Planner/models/pretrained_net_final_20220825.pth"

OUTPUT_DIR   = os.environ.get(
    "OUTPUT_DIR",
    os.path.join(os.path.dirname(PATCHES_DIR), "finetuned_models"),
)
os.makedirs(OUTPUT_DIR, exist_ok=True)

# ---------------------------------------------------------------------------
# HYPER-PARAMETERS
# ---------------------------------------------------------------------------
EPOCHS         = 80
BATCH_SIZE     = 2
LR             = 5e-5        # higher LR for decoder (encoder frozen)
FREEZE_ENCODER = True        # freeze encoder to preserve pretrained knowledge
VAL_SPLIT      = 0.15
NUM_WORKERS    = 2
SEED           = 42
PATIENCE       = 20
SAVE_EVERY     = 10

# Knowledge distillation weights
TASK_ALPHA     = 1.0         # weight for L1(pred, ct_target)
DISTILL_ALPHA  = 0.3         # mild regularizer — allows vertebrae adaptation

# ---------------------------------------------------------------------------
# IMPORT NETWORK
# ---------------------------------------------------------------------------
sys.path.insert(0, os.path.abspath(SITINY_REPO))
from utils.netdef import ShuffleUNet          # noqa: E402

# ---------------------------------------------------------------------------
# DATASET
# ---------------------------------------------------------------------------
class PatchDataset(Dataset):
    """Loads paired *_mri.npy / *_ct.npy patches and returns (1,Z,Y,X) tensors."""

    def __init__(self, patches_dir: str, augment: bool = False):
        mri_files = sorted(glob.glob(os.path.join(patches_dir, "*_mri.npy")))
        if not mri_files:
            raise FileNotFoundError(f"No *_mri.npy files found in: {patches_dir}")
        # Keep only pairs where both files exist
        self.pairs = []
        for mf in mri_files:
            cf = mf.replace("_mri.npy", "_ct.npy")
            if os.path.exists(cf):
                self.pairs.append((mf, cf))
        if not self.pairs:
            raise FileNotFoundError("No complete MRI/CT pairs found.")
        self.augment = augment
        print(f"  PatchDataset: {len(self.pairs)} pairs (augment={augment})")

    def __len__(self):
        return len(self.pairs)

    def __getitem__(self, idx):
        mri = np.load(self.pairs[idx][0]).astype(np.float32)
        ct  = np.load(self.pairs[idx][1]).astype(np.float32)

        # CT patches were saved normalised to [-1, 1] via normalise_ct:
        #   arr = (arr_hu + 1000) / 1500.0 - 1.0
        # Invert to HU so the fine-tuning target matches the pretrained output scale.
        ct = (ct + 1.0) * 1500.0 - 1000.0

        # Ensure shape is (Z, Y, X); add channel dim → (1, Z, Y, X)
        mri = np.expand_dims(mri, 0)
        ct  = np.expand_dims(ct,  0)

        if self.augment:
            for ax in range(1, 4):
                if np.random.rand() > 0.5:
                    mri = np.flip(mri, axis=ax).copy()
                    ct  = np.flip(ct,  axis=ax).copy()

        return torch.from_numpy(mri), torch.from_numpy(ct)


# ---------------------------------------------------------------------------
# TRAINING LOOP
# ---------------------------------------------------------------------------
def train():
    torch.manual_seed(SEED)
    np.random.seed(SEED)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"\n{'='*60}")
    print(f"FINE-TUNING SITINY ShuffleUNet")
    print(f"{'='*60}")
    print(f"  Device      : {device}")
    print(f"  Patches dir : {PATCHES_DIR}")
    print(f"  Pretrained  : {MODEL_IN}")
    print(f"  Output dir  : {OUTPUT_DIR}")
    print(f"  Epochs      : {EPOCHS}  |  LR: {LR}  |  Batch: {BATCH_SIZE}")

    # --- Data ---
    full_ds = PatchDataset(PATCHES_DIR, augment=True)
    n_val   = max(1, int(len(full_ds) * VAL_SPLIT))
    n_train = len(full_ds) - n_val
    train_ds, val_ds = random_split(
        full_ds, [n_train, n_val],
        generator=torch.Generator().manual_seed(SEED),
    )
    # Disable augmentation on val subset
    val_ds.dataset = copy.copy(full_ds)
    val_ds.dataset.augment = False

    train_loader = DataLoader(train_ds, batch_size=BATCH_SIZE, shuffle=True,
                              num_workers=NUM_WORKERS, pin_memory=(device.type == "cuda"))
    val_loader   = DataLoader(val_ds,   batch_size=1,          shuffle=False,
                              num_workers=NUM_WORKERS, pin_memory=(device.type == "cuda"))

    print(f"  Train patches: {n_train}  |  Val patches: {n_val}")

    # --- Model: student (to be fine-tuned) ---
    net = ShuffleUNet(
        dimensions=3, in_channels=1, out_channels=1,
        channels=(32, 64, 128, 256, 512), strides=(2, 2, 2, 2),
        kernel_size=3, up_kernel_size=3, num_res_units=2,
    ).to(device)

    if not os.path.exists(MODEL_IN):
        print(f"\n[WARNING] Pretrained weights not found at: {MODEL_IN}")
        print("  Training from scratch (random initialisation).")
        teacher = None
    else:
        state = torch.load(MODEL_IN, map_location=device)
        net.load_state_dict(state)
        print(f"\n  Loaded pretrained weights from: {MODEL_IN}")

        # --- Teacher: frozen copy of pretrained model for distillation ---
        teacher = ShuffleUNet(
            dimensions=3, in_channels=1, out_channels=1,
            channels=(32, 64, 128, 256, 512), strides=(2, 2, 2, 2),
            kernel_size=3, up_kernel_size=3, num_res_units=2,
        ).to(device)
        teacher.load_state_dict(state)
        for p in teacher.parameters():
            p.requires_grad = False
        teacher.eval()
        print(f"  Teacher (frozen pretrained) loaded for distillation.")

    # --- Freeze encoder (optional, now handled by distillation) ---
    if FREEZE_ENCODER:
        total_params  = list(net.parameters())
        freeze_until  = len(total_params) // 2
        for i, p in enumerate(total_params):
            if i < freeze_until:
                p.requires_grad = False
        trainable = sum(p.numel() for p in net.parameters() if p.requires_grad)
        total     = sum(p.numel() for p in net.parameters())
        print(f"  Encoder frozen. Trainable params: {trainable:,} / {total:,}")
    else:
        print(f"  All params trainable (distillation prevents forgetting).")

    # --- Loss & optimiser ---
    task_criterion    = nn.L1Loss()
    distill_criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(filter(lambda p: p.requires_grad, net.parameters()), lr=LR)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="min", factor=0.5, patience=7,
    )

    # --- Training ---
    best_val_loss  = float("inf")
    best_epoch     = 0
    patience_count = 0
    history        = []

    for epoch in range(1, EPOCHS + 1):
        t0 = time.time()

        # -- train --
        net.train()
        train_loss = 0.0
        for mri_batch, ct_batch in train_loader:
            mri_batch = mri_batch.to(device)
            ct_batch  = ct_batch.to(device)
            optimizer.zero_grad()
            pred = net(mri_batch)

            # Task loss: L1 between prediction and ground-truth CT
            loss = TASK_ALPHA * task_criterion(pred, ct_batch)

            # Distillation loss: keep student close to teacher (prevents forgetting)
            if teacher is not None:
                with torch.no_grad():
                    teacher_pred = teacher(mri_batch)
                loss = loss + DISTILL_ALPHA * distill_criterion(pred, teacher_pred)

            loss.backward()
            optimizer.step()
            train_loss += loss.item() * len(mri_batch)
        train_loss /= n_train

        # -- validate --
        net.eval()
        val_loss = 0.0
        with torch.no_grad():
            for mri_batch, ct_batch in val_loader:
                mri_batch  = mri_batch.to(device)
                ct_batch   = ct_batch.to(device)
                pred       = net(mri_batch)
                batch_loss = TASK_ALPHA * task_criterion(pred, ct_batch)
                if teacher is not None:
                    teacher_pred = teacher(mri_batch)
                    batch_loss   = batch_loss + DISTILL_ALPHA * distill_criterion(pred, teacher_pred)
                val_loss += batch_loss.item() * len(mri_batch)
        val_loss /= n_val

        scheduler.step(val_loss)
        dt = time.time() - t0

        print(f"  Epoch {epoch:>3}/{EPOCHS}  "
              f"train_loss={train_loss:.5f}  val_loss={val_loss:.5f}  "
              f"({dt:.1f}s)")

        history.append({"epoch": epoch, "train": train_loss, "val": val_loss})

        # -- best model --
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_epoch    = epoch
            patience_count = 0
            best_path = os.path.join(OUTPUT_DIR, "finetuned_best.pth")
            torch.save(net.state_dict(), best_path)
            print(f"    ✓ New best model saved  (val_loss={best_val_loss:.5f})")
        else:
            patience_count += 1

        # -- periodic checkpoint --
        if epoch % SAVE_EVERY == 0:
            ckpt_path = os.path.join(OUTPUT_DIR, f"finetuned_epoch{epoch:03d}.pth")
            torch.save(net.state_dict(), ckpt_path)
            print(f"    Checkpoint saved: {ckpt_path}")

        # -- early stopping --
        if patience_count >= PATIENCE:
            print(f"\n  Early stopping at epoch {epoch} "
                  f"(no improvement for {PATIENCE} epochs).")
            break

    # --- Save final model ---
    final_path = os.path.join(OUTPUT_DIR, "finetuned_final.pth")
    torch.save(net.state_dict(), final_path)

    # --- Save training log ---
    log_path = os.path.join(OUTPUT_DIR, "training_log.csv")
    with open(log_path, "w") as f:
        f.write("epoch,train_loss,val_loss\n")
        for row in history:
            f.write(f"{row['epoch']},{row['train']:.6f},{row['val']:.6f}\n")

    print(f"\n{'='*60}")
    print(f"Training complete.")
    print(f"  Best epoch  : {best_epoch}  (val_loss={best_val_loss:.5f})")
    print(f"  Best model  : {best_path}")
    print(f"  Final model : {final_path}")
    print(f"  Training log: {log_path}")
    print(f"{'='*60}\n")


if __name__ == "__main__":
    train()
